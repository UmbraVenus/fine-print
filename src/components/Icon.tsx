export type IconName = keyof typeof STROKE
export type FilledIconName = keyof typeof FILLED

export function Icon({
  name,
  size = 18,
  strokeWidth = 2,
  color,
  style,
}: {
  name: IconName
  size?: number
  strokeWidth?: number
  color?: string
  style?: CSSProperties
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color ?? 'currentColor'}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      style={{ flexShrink: 0, ...style }}
    >
      {STROKE[name]}
    </svg>
  )
}

export function FilledIcon({ name, size = 16, strokeWidth = 2.2 }: { name: FilledIconName; size?: number; strokeWidth?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" focusable="false" style={{ flexShrink: 0 }}>
      <circle cx="12" cy="12" r="11" fill="currentColor" />
      <g strokeWidth={strokeWidth}>{FILLED[name]}</g>
    </svg>
  )
}

